import AbstractGatewayClient
import SwiftUI
import WatchKit

/// Settings → Voice: the speaking voice and the transcription model, from what the gateway offers
/// (the gateway's default first). Kept on this watch; the gateway's defaults are not changed. A
/// voice plays a short sample when chosen. The voices come in groups (your voices, the engine's,
/// the shared ones) with their language, and a "Voices that speak" filter when the catalog speaks
/// several; voices are created on the iPhone or the desktop.
struct VoiceSettingsView: View {
    @EnvironmentObject private var model: AppModel
    @StateObject private var speaker = Speaker()
    @State private var catalog: VoiceCatalog?
    @State private var failed = false
    @State private var voice = VoicePrefs.voice
    @State private var transcription = VoicePrefs.transcription
    @State private var speed = VoicePrefs.speed
    /// The voice whose sample is being made (its row shows a spinner until it speaks).
    @State private var previewing: String?
    /// The language the voice list keeps ("": every voice).
    @State private var language = ""

    var body: some View {
        Group {
            if catalog != nil { list }
            else if failed {
                Text("Couldn't load the voices").font(.rounded(.footnote)).foregroundStyle(Theme.muted)
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                // Until the gateway answers (a few seconds on a watch): a spinner, not a half page.
                VStack(spacing: 8) {
                    ProgressView()
                    Text("Loading voices…").font(.rounded(.footnote)).foregroundStyle(Theme.muted)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
                .accessibilityElement(children: .combine)
                .accessibilityIdentifier("voices.loading")
            }
        }
        .screen("Voice")
        .task {
            do { catalog = try await model.client.voiceCatalog() } catch { failed = true }
        }
        .onDisappear { speaker.stop() }
    }

    private var list: some View {
        List {
            Section("Speaking voice") {
                if languages.count > 1 {
                    Picker("Voices that speak", selection: $language) {
                        Text("Any language").tag("")
                        ForEach(languages, id: \.self) { Text(VoiceLibrary.languageName($0)).tag($0) }
                    }
                    .font(.rounded(.footnote))
                    .accessibilityIdentifier("voices.language")
                }
                choice("Gateway default", detail: catalog?.defaultVoice, selected: voice == nil, loading: generating("default")) { pickVoice(nil) }
            }
            ForEach(VoiceLibrary.grouped(catalog?.entries ?? [], speaking: language, keep: voice), id: \.group) { section in
                Section(section.group.title) {
                    ForEach(section.entries) { entry in
                        choice(entry.choice.label, detail: Self.detail(entry), selected: voice?.id == entry.id, loading: generating(entry.id)) { pickVoice(entry.choice) }
                    }
                }
            }
            Section {
                Text("Create voices on the iPhone or the desktop.")
                    .font(.rounded(.caption2)).foregroundStyle(Theme.muted)
                    .accessibilityIdentifier("voices.createElsewhere")
            }
            Section("Speed") {
                ForEach(VoicePrefs.speeds, id: \.self) { s in
                    choice(Self.label(speed: s), detail: nil, selected: speed == s, loading: generating("speed-\(s)")) { pickSpeed(s) }
                }
            }
            Section {
                choice("Gateway default", detail: catalog?.defaultTranscription, selected: transcription == nil) { pickTranscription(nil) }
                ForEach(catalog?.transcription ?? []) { t in
                    choice(t.model, detail: Self.hint(t.model), selected: transcription == t) { pickTranscription(t) }
                }
            } header: {
                Text("Transcription")
            } footer: {
                Text("Larger models understand better and take longer.")
            }
        }
    }

    private var languages: [String] { VoiceLibrary.languages(of: catalog?.entries ?? []) }

    /// "French · female": a voice's language and what else the gateway says of it.
    static func detail(_ entry: VoiceEntry) -> String? {
        let parts = [entry.language.map(VoiceLibrary.languageName), entry.choice.gender].compactMap { $0 }.filter { !$0.isEmpty }
        return parts.isEmpty ? nil : parts.joined(separator: " · ")
    }

    /// The sample of this row is being generated by the gateway (before its first sound).
    private func generating(_ id: String) -> Bool { previewing == id && speaker.state == .preparing }

    private func choice(_ title: String, detail: String?, selected: Bool, loading: Bool = false, pick: @escaping () -> Void) -> some View {
        Button(action: pick) {
            HStack {
                VStack(alignment: .leading, spacing: 1) {
                    Text(title).font(.rounded(.footnote, weight: .semibold)).foregroundStyle(Theme.text)
                    if let detail, !detail.isEmpty {
                        Text(detail).font(.rounded(.caption2)).foregroundStyle(Theme.muted)
                    }
                }
                Spacer(minLength: 4)
                if loading { ProgressView().frame(width: 18, height: 18).accessibilityLabel("Making the sample") }
                else if selected { Image(systemName: "checkmark").foregroundStyle(Theme.cyan) }
            }
        }
        .accessibilityAddTraits(selected ? .isSelected : [])
    }

    /// Chosen, then heard: a short sample in that voice (the Assistant's voice from now on).
    private func pickVoice(_ v: VoiceChoice?) {
        voice = v
        VoicePrefs.voice = v
        previewing = v?.id ?? "default"
        WKInterfaceDevice.current().play(.click)
        speaker.read("Hello, I'm AbstractAssistant.", scope: .run("session_memory_\(model.askSessionId)"), client: model.client)
    }

    /// Chosen, then heard: the sample in the chosen voice at that speed.
    private func pickSpeed(_ s: Double) {
        speed = s
        VoicePrefs.speed = s
        previewing = "speed-\(s)"
        WKInterfaceDevice.current().play(.click)
        speaker.read("Hello, I'm AbstractAssistant.", scope: .run("session_memory_\(model.askSessionId)"), client: model.client)
    }

    static func label(speed s: Double) -> String {
        s == 1 ? "Normal" : s.formatted(.number.precision(.fractionLength(0...2))) + "×"
    }

    private func pickTranscription(_ t: TranscriptionChoice?) {
        transcription = t
        VoicePrefs.transcription = t
        WKInterfaceDevice.current().play(.click)
    }

    /// A word on the size of a transcription model.
    static func hint(_ model: String) -> String? {
        switch model {
        case "tiny": "fastest"
        case "base": "fast"
        case "small": "balanced"
        case "medium": "accurate"
        case "large", "large-v2", "large-v3": "most accurate, slowest"
        case "large-v3-turbo", "turbo": "accurate, faster than large"
        default: nil
        }
    }
}
